    return GetAssistantHistoryResult(
      success: json['success'] == true,
      messages: parsedMessages,
      offers: parsedOffers,
      revision: (json['revision'] as num?)?.toInt() ?? 0,
      resetAt: parsedResetAt,
      status: parsedStatus,
